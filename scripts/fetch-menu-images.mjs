// Downloads four topic-matched photos per service for the header's Services menu into public/images/menu/,
// then writes lib/menu-images.ts so each tile fades through its own set. Existing site photos are not touched.
//
//   PIXABAY_API_KEY=your_key node scripts/fetch-menu-images.mjs
import { existsSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";

import { download, findPhoto, requireKey } from "./stock-photos.mjs";

const out = new URL("../public/images/menu/", import.meta.url);

const services = {
  "networking-and-infrastructure": ["network switch cables", "wifi router office network", "network engineer server rack", "fiber optic cables"],
  "software-development-services": ["software developer coding", "web design laptop", "programmer team office", "mobile app development"],
  "it-support-and-helpdesk": ["customer support headset", "it technician laptop repair", "help desk team", "computer troubleshooting"],
  "managed-it-services": ["network operations center", "server room administrator", "it monitoring dashboard", "data center technician"],
  "cybersecurity-services": ["cyber security lock", "hacker security code", "firewall protection digital", "data protection shield"],
  "cloud-services": ["cloud computing technology", "cloud storage server", "digital cloud network", "data center cloud"],
  "digital-marketing-services": ["digital marketing laptop", "social media marketing", "seo analytics", "online advertising team"],
  recruitment: ["job interview", "hr recruiter resume", "hiring team handshake", "candidate interview office"],
};

requireKey();
await mkdir(out, { recursive: true });
const used = new Set();
const credits = [];
const saved = {};

for (const [slug, queries] of Object.entries(services)) {
  saved[slug] = [];
  for (const [i, query] of queries.entries()) {
    const name = `${slug}-${i + 1}.jpg`;
    // Re-running picks up where an interrupted run stopped.
    if (existsSync(new URL(name, out))) {
      saved[slug].push(name);
      console.log(`kept   ${name}`);
      continue;
    }
    const photo = await findPhoto(query, used);
    if (!photo) {
      console.warn(`none   ${name}: nothing found for "${query}"`);
      continue;
    }
    let data = null;
    for (let attempt = 1; attempt <= 3 && !data; attempt++) {
      try {
        data = await download(photo.url);
      } catch (error) {
        console.warn(`wait   ${name}: rate limited, pausing 60s (attempt ${attempt}/3)`);
        await new Promise((resolve) => setTimeout(resolve, 60_000));
      }
    }
    if (!data) {
      console.warn(`skip   ${name}`);
      continue;
    }
    await writeFile(new URL(name, out), data);
    saved[slug].push(name);
    credits.push(`${name}	${photo.credit}	${photo.page}`);
    console.log(`saved  ${name}  <-  "${query}"  (${photo.credit})`);
  }
}

await writeFile(new URL("CREDITS.txt", out), credits.join("\n") + "\n");

const names = (file) => file.replace(/\.jpg$/, "").replace(/-(\w)/g, (_, c) => c.toUpperCase()).replace(/^(\d)/, "_$1");
const lines = [
  "// Photos that fade through each service tile in the header's Services menu (components/site-header.tsx).",
  "// Generated by scripts/fetch-menu-images.mjs from public/images/menu/. To use your own pictures, put them in that",
  "// folder and list them here: a tile cycles through whatever is listed for its page, in order.",
  'import type { StaticImageData } from "next/image";',
  "",
];
for (const files of Object.values(saved)) {
  for (const file of files) lines.push(`import ${names(file)} from "@/public/images/menu/${file}";`);
}
lines.push("", "export const menuImages: Record<string, StaticImageData[]> = {");
for (const [slug, files] of Object.entries(saved)) {
  lines.push(`  "/${slug}": [${files.map(names).join(", ")}],`);
}
lines.push("};", "");
await writeFile(new URL("../lib/menu-images.ts", import.meta.url), lines.join("\n"));
console.log("Done. lib/menu-images.ts updated.");
