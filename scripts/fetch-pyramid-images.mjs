// Downloads one upright, topic-matched photo per service for the faces of the About page's pyramid into
// public/images/pyramid/, then writes lib/pyramid-images.ts. Upright photos suit the triangular faces, whose
// middle shows most. Safe to re-run: files that already exist are kept.
//
//   PIXABAY_API_KEY=your_key node scripts/fetch-pyramid-images.mjs
import { existsSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";

import { download, requireKey } from "./stock-photos.mjs";

const out = new URL("../public/images/pyramid/", import.meta.url);

const services = {
  "networking-and-infrastructure": ["ethernet cable network switch", "network cables server"],
  "software-development-services": ["programming code on screen", "software developer coding"],
  "it-support-and-helpdesk": ["customer support headset", "it help desk support"],
  "managed-it-services": ["data center server rack", "server room technician"],
  "cybersecurity-services": ["cyber security", "data protection hacker", "digital security password"],
  "cloud-services": ["cloud computing", "cloud storage technology", "cloud network"],
  "digital-marketing-services": ["digital marketing", "seo analytics", "social media marketing"],
  recruitment: ["job interview", "business handshake", "recruitment hiring"],
};

requireKey();
await mkdir(out, { recursive: true });
const key = process.env.PIXABAY_API_KEY;
const used = new Set();
const credits = [];
const saved = {};

/** Words a photo's tags must contain, so a search for "cloud computing" cannot return the sky. */
const topic = {
  "networking-and-infrastructure": /network|cable|ethernet|server|switch|router/i,
  "software-development-services": /code|coding|program|software|developer|computer/i,
  "it-support-and-helpdesk": /support|help|headset|customer|call center|service/i,
  "managed-it-services": /server|data center|rack|network|technology|computer/i,
  "cybersecurity-services": /security|cyber|lock|hacker|protection|password/i,
  "cloud-services": /cloud computing|cloud storage|cloud|data|server|network/i,
  "digital-marketing-services": /marketing|seo|social media|analytics|advertis|business/i,
  recruitment: /interview|job|recruit|hiring|handshake|business|career/i,
};
const notTopic = /sky|sunset|weather|storm|bus|van|camper|book|toy|animal|heart|love|paper|cv|wedding/i;

async function search(query, slug) {
  const params = new URLSearchParams({
    key,
    q: query,
    image_type: "photo",
    min_width: "700",
    safesearch: "true",
    order: "popular",
    per_page: "20",
  });
  const res = await fetch(`https://pixabay.com/api/?${params}`);
  if (!res.ok) throw new Error(`Pixabay search failed (${res.status}) for "${query}"`);
  const { hits = [] } = await res.json();
  return hits.find((hit) => !used.has(hit.id) && topic[slug].test(hit.tags) && !notTopic.test(hit.tags)) ?? null;
}

for (const [slug, queries] of Object.entries(services)) {
  const name = `${slug}.jpg`;
  if (existsSync(new URL(name, out))) {
    saved[slug] = name;
    console.log(`kept   ${name}`);
    continue;
  }
  let hit = null;
  for (const query of queries) {
    hit = await search(query, slug);
    if (hit) break;
  }
  if (!hit) {
    console.warn(`none   ${name}`);
    continue;
  }
  used.add(hit.id);
  let data = null;
  for (let attempt = 1; attempt <= 3 && !data; attempt++) {
    try {
      data = await download(hit.largeImageURL);
    } catch {
      console.warn(`wait   ${name}: rate limited, pausing 60s (attempt ${attempt}/3)`);
      await new Promise((resolve) => setTimeout(resolve, 60_000));
    }
  }
  if (!data) {
    console.warn(`skip   ${name}`);
    continue;
  }
  await writeFile(new URL(name, out), data);
  saved[slug] = name;
  credits.push(`${name}\t${hit.user} / Pixabay\t${hit.pageURL}`);
  console.log(`saved  ${name}  (${hit.user} / Pixabay)  tags: ${hit.tags}`);
}

await writeFile(new URL("CREDITS.txt", out), credits.join("\n") + "\n");

const ident = (file) => "pyramid" + file.replace(/\.jpg$/, "").replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());
const lines = [
  "// The photo on each face of the About page's pyramid, one per service page (components/cube-gallery.tsx).",
  "// Generated by scripts/fetch-pyramid-images.mjs from public/images/pyramid/; swap a file there to change a face.",
  'import type { StaticImageData } from "next/image";',
  "",
];
for (const file of Object.values(saved)) lines.push(`import ${ident(file)} from "@/public/images/pyramid/${file}";`);
lines.push("", "export const pyramidImages: Record<string, StaticImageData> = {");
for (const [slug, file] of Object.entries(saved)) lines.push(`  "/${slug}": ${ident(file)},`);
lines.push("};", "");
await writeFile(new URL("../lib/pyramid-images.ts", import.meta.url), lines.join("\n"));
console.log("Done. lib/pyramid-images.ts updated.");
